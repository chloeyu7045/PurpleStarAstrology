/** 廟旺利陷 → 這股特質的力道 */
function strengthNote(brightness) {
  if (['廟', '旺'].includes(brightness)) return '而且這股特質在你身上特別明顯、特別強。';
  if (['陷', '不'].includes(brightness)) return '不過這股特質在你身上發揮得不太順，你可能常覺得「我知道自己該是這樣，但就是使不出來」。';
  return '';
}

