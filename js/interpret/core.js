/**
 * 取出這個人的核心解讀。任何配置都查得到，包含命宮無主星（借對宮）。
 */
export function coreReading(astrolabe) {
  const ming = astrolabe.palaces.find((p) => p.name === '命宮');
  if (!ming) return null;

  const opp = astrolabe.palaces[((ming.index + 6) % 12 + 12) % 12];
  const borrowed = ming.majorStars.length === 0;
  const stars = borrowed ? opp.majorStars : ming.majorStars;
  if (!stars.length) return null;

  const entry = T[K(stars.map((s) => s.name))];
  if (!entry) return null;

  // 力道：取最亮的那顆當代表
  const order = ['廟', '旺', '得', '利', '平', '不', '陷'];
  const best = stars.map((s) => s.brightness).filter(Boolean)
    .sort((a, b) => order.indexOf(a) - order.indexOf(b))[0] || '';

  const mutagens = [...ming.majorStars, ...ming.minorStars]
    .map((s) => s.mutagen).filter(Boolean);

  const extras = [];
  const note = strengthNote(best);
  if (note) extras.push(note);
  mutagens.forEach((m) => { if (MUTAGEN_NOTE[m]) extras.push(MUTAGEN_NOTE[m]); });
  if (borrowed) {
    extras.push('另外，你的樣子很容易被身邊的環境和人帶著走——你選擇待在哪裡、跟誰在一起，幾乎就決定了你會變成誰。');
  }

  return { ...entry, extras };
}

