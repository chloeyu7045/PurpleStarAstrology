const MUT_ORDER = ['祿', '權', '科', '忌'];

/** 找出某顆星在這張盤的哪一宮 */
function palaceOfStar(palaces, name) {
  const p = palaces.find((x) =>
    [...x.majorStars, ...x.minorStars].some((s) => s.name === name));
  return p ? p.name : null;
}

/** 取這張盤的生年四化：[{type, star}] */
export function birthMutagens(astrolabe) {
  const found = {};
  astrolabe.palaces.forEach((p) => {
    [...p.majorStars, ...p.minorStars].forEach((s) => {
      if (s.mutagen && !found[s.mutagen]) found[s.mutagen] = s.name;
    });
  });
  return MUT_ORDER.filter((t) => found[t]).map((t) => ({ type: t, star: found[t] }));
}

/**
 * 算出 from 的四化飛進 to 的哪些宮位。
 * 回傳 [{type, palace, text}]，text 已經是白話。
 */
export function fliesInto(fromAstro, toAstro, fromName, toName) {
  const muts = birthMutagens(fromAstro);
  const out = [];
  muts.forEach(({ type, star }) => {
    const palace = palaceOfStar(toAstro.palaces, star);
    if (!palace || !FLY[type] || !FLY[type][palace]) return;
    out.push({
      type,
      palace,
      text: FLY[type][palace].replace(/\{A\}/g, fromName).replace(/\{B\}/g, toName),
    });
  });
  return out;
}

/** 兩人命宮地支的關係：三合、六沖、六合，其餘為一般 */
const BRANCHES = ['子', '丑', '寅', '卯', '辰', '巳', '午', '未', '申', '酉', '戌', '亥'];
const LIUHE = { 子: '丑', 丑: '子', 寅: '亥', 亥: '寅', 卯: '戌', 戌: '卯', 辰: '酉', 酉: '辰', 巳: '申', 申: '巳', 午: '未', 未: '午' };

export function branchRelation(b1, b2) {
  if (!b1 || !b2) return null;
  const i1 = BRANCHES.indexOf(b1);
  const i2 = BRANCHES.indexOf(b2);
  if (i1 < 0 || i2 < 0) return null;
  const diff = ((i2 - i1) % 12 + 12) % 12;
  if (b1 === b2) {
    return { key: 'same', title: '你們是同一種頻率的人',
      text: '你們對事情的反應、在意的點、甚至說話的節奏都很像。好處是不用解釋對方就懂；壞處是你們的盲點也一模一樣，沒有人能提醒對方。' };
  }
  if (diff === 6) {
    return { key: 'clash', title: '你們天生就是互相拉扯的組合',
      text: '你們看事情的角度幾乎是相反的，很容易一言不合。但這種相反不是壞事——對方剛好補上你缺的那一半，前提是你們願意聽。' };
  }
  if (diff === 4 || diff === 8) {
    return { key: 'trine', title: '你們天生合得來',
      text: '你們在一起是省力的。價值觀接近、節奏對得上，不太需要磨合就能一起做事。要小心的是太舒服了，反而不會互相刺激。' };
  }
  if (LIUHE[b1] === b2) {
    return { key: 'harmony', title: '你們容易黏在一起',
      text: '你們之間有一種天然的吸引和依賴，容易愈走愈近。好的時候非常緊密，但也容易分不開、界線變模糊。' };
  }
  return null;
}
